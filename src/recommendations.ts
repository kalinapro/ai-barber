function getScore(
  table: Record<string, number> | undefined,
  answer: string | undefined,
) {
  if (!table || !answer) {
    return 0;
  }

  return table[answer] ?? 0;
}

function getFaceBonus(
  faceShapeScore: number,
  faceShape: string | undefined,
) {
  if (!faceShape || faceShape === 'Не знаю') {
    return 0;
  }

  if (faceShapeScore === 5) {
    return 15;
  }

  if (faceShapeScore === 4) {
    return 9;
  }

  if (faceShapeScore === 3) {
    return 2;
  }

  if (faceShapeScore === 2) {
    return -8;
  }

  if (faceShapeScore === 1) {
    return -15;
  }

  return -25;
}

export function getRecommendations(
  answers: BarberAnswers,
): Recommendation[] {
  const result = hairstyles.map((hairstyle) => {
    const lengthScore = getScore(
      hairstyle.scores.hairLength,
      answers.hairLength,
    );

    const styleScore = getScore(
      hairstyle.scores.style,
      answers.style,
    );

    const changeScore = getScore(
      hairstyle.scores.changeLevel,
      answers.changeLevel,
    );

    const stylingScore = getScore(
      hairstyle.scores.stylingTime,
      answers.stylingTime,
    );

    const featureScore = getScore(
      hairstyle.scores.hairFeatures,
      answers.hairFeatures,
    );

    const faceShapeScore = getScore(
      hairstyle.scores.faceShape,
      answers.faceShape,
    );

    const faceBonus = getFaceBonus(
      faceShapeScore,
      answers.faceShape,
    );

    const score =
      lengthScore +
      styleScore +
      changeScore +
      stylingScore +
      featureScore +
      faceBonus;

    const reasons: string[] = [];

    if (
      faceShapeScore >= 4 &&
      answers.faceShape &&
      answers.faceShape !== 'Не знаю'
    ) {
      reasons.push(
        `подходит для формы лица «${answers.faceShape}»`,
      );
    }

    if (lengthScore >= 4) {
      reasons.push(
        'подходит к твоей текущей длине волос',
      );
    }

    if (styleScore >= 4) {
      reasons.push(
        'соответствует выбранному стилю',
      );
    }

    if (stylingScore >= 4) {
      reasons.push(
        'подходит под желаемое время на укладку',
      );
    }

    if (featureScore >= 4) {
      reasons.push(
        'учитывает особенности твоих волос',
      );
    }

    if (changeScore >= 4) {
      reasons.push(
        'соответствует желаемой степени изменения образа',
      );
    }

    return {
      ...hairstyle,
      score,
      reasons,
    };
  });

  return result.sort(
    (a, b) => b.score - a.score,
  );
}
